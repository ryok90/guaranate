#!/usr/bin/env node
// Generates the published changelog from the repository's release history.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const docsDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(docsDir, '..');
const sourcePath = join(repoRoot, 'CHANGELOG.md');
const outputPath = join(docsDir, 'src/content/docs/reference/changelog.md');

const source = readFileSync(sourcePath, 'utf8');
if (!source.startsWith('# Changelog\n\n')) {
  throw new Error('CHANGELOG.md must start with # Changelog followed by a blank line');
}

const body = source.slice('# Changelog\n\n'.length);
const heading = '## [Unreleased]';
const matches = [...body.matchAll(/^## \[Unreleased\]$/gm)];
if (matches.length !== 1) {
  throw new Error('CHANGELOG.md must contain exactly one ## [Unreleased] heading');
}

const beforeUnreleased = body.slice(0, matches[0].index).replace(
  /^Add user-facing entries under[^\n]*(?:\n(?!\n)[^\n]*)*\n\n/m,
  '',
);
const afterUnreleased = body.slice(matches[0].index + heading.length);
const content = `---
title: Changelog
description: Guaranate release history and changes not yet released.
editUrl: https://github.com/ryok90/guaranate/edit/main/CHANGELOG.md
lastUpdated: false
---

<!-- Generated by scripts/gen-changelog.mjs from CHANGELOG.md; do not edit. -->

${beforeUnreleased}${heading}

:::caution[Not yet released]
Changes listed here have not been included in a tagged release.
:::${afterUnreleased}`;

writeFileSync(outputPath, content);
